export function enrichExistingArticles(articles: Article[]) {
  for (const a of articles) {
    const guide = guides[a.id];
    if (!guide) continue;
    a.keyPoints = guide.keyPoints;
    a.terms = guide.terms;
    for (const s of a.sections) {
      s.highlights ??= phrases.filter((p) => s.text.includes(p)).slice(0, 2);
    }
    for (const section of guide.sections) {
      if (!a.sections.some((existing) => existing.title === section.title))
        a.sections.push(section);
    }
  }
}
